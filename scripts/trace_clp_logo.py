"""Traces the Chez Les Petits logo (small PNG, black line art on transparent) into a crisp SVG.

Writes src/chezlespetits/cloud.ts (the bare cloud outline) and public/chez-les-petits/logo.svg with three layers: `halo` (a white outline around the
ink), `fill` (the cloud's interior), so the logo sits as a white sticker on any photo, and
`ink` (the line art itself).

usage: python3 -I scripts/trace_clp_logo.py <logo.png>
"""
import sys

import numpy as np
import potrace
from PIL import Image
from scipy import ndimage

UP = 8  # trace at 8x so curves come out smooth

src = Image.open(sys.argv[1]).convert('RGBA')
w, h = src.size
big = src.resize((w * UP, h * UP), Image.LANCZOS)
rgba = np.asarray(big).astype(float) / 255
# Ink = opaque and dark.
ink = (rgba[..., 3] > 0.5) & (rgba[..., :3].mean(axis=2) < 0.5)

# Interior of the cloud: everything the outside cannot reach without crossing ink.
outside = ndimage.label(~ink)[0]
border = set(np.unique(np.concatenate([outside[0], outside[-1], outside[:, 0], outside[:, -1]])))
fill = ~np.isin(outside, list(border)) | ink
fill = ndimage.binary_fill_holes(fill)


def to_path(mask):
	# potracer treats falsy (dark) pixels as the shape.
	curves = potrace.Bitmap(~mask).trace(turdsize=8, alphamax=1.0, opticurve=True, opttolerance=0.2)
	parts = []
	for curve in curves:
		sx, sy = curve.start_point.x, curve.start_point.y
		d = [f'M{sx / UP:.2f},{sy / UP:.2f}']
		for seg in curve.segments:
			if seg.is_corner:
				d.append(f'L{seg.c.x / UP:.2f},{seg.c.y / UP:.2f}L{seg.end_point.x / UP:.2f},{seg.end_point.y / UP:.2f}')
			else:
				d.append(
					f'C{seg.c1.x / UP:.2f},{seg.c1.y / UP:.2f} {seg.c2.x / UP:.2f},{seg.c2.y / UP:.2f} '
					f'{seg.end_point.x / UP:.2f},{seg.end_point.y / UP:.2f}'
				)
		parts.append(''.join(d) + 'Z')
	return ''.join(parts)


ink_path = to_path(ink)
svg = (
	f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">'
	# A white halo traced around the ink keeps the tagline under the cloud readable on photos.
	f'<path id="halo" d="{ink_path}" fill="#ffffff" stroke="#ffffff" stroke-width="3.4" stroke-linejoin="round"/>'
	f'<path id="fill" d="{to_path(fill)}" fill="#ffffff" fill-rule="evenodd"/>'
	f'<path id="ink" d="{ink_path}" fill="#000000" fill-rule="evenodd"/>'
	'</svg>'
)
open('public/chez-les-petits/logo.svg', 'w').write(svg)

# The cloud on its own (largest filled shape, tagline dropped), cropped to its bounds, for
# photo masks and icons.
parts, n = ndimage.label(fill)
cloud = parts == (np.argmax(np.bincount(parts.ravel())[1:]) + 1)
ys, xs = np.nonzero(cloud)
cloud = cloud[ys.min() : ys.max() + 1, xs.min() : xs.max() + 1]
ch, cw = cloud.shape
open('src/chezlespetits/cloud.ts', 'w').write(
	'// Generated by scripts/trace_clp_logo.py: the Chez Les Petits logo cloud as a path.\n'
	f'export const CLOUD = {{width: {cw / UP:.2f}, height: {ch / UP:.2f}, d: {to_path(cloud)!r}}};\n'
)
print('fill px', int(fill.sum()), 'ink px', int(ink.sum()))
